import assert from 'node:assert/strict';
import {createProgress} from '../src/systems/progress.js';
import {STORIES} from '../src/data/live-content.js';
const storage=new Map();globalThis.localStorage={getItem:key=>storage.get(key)||null,setItem:(key,value)=>storage.set(key,value)};
const seed=createProgress('free-explore');seed.state.chapter[0].counts=[2,0];seed.state.activeStory=STORIES[0]?.id||null;
storage.set('free-explore',JSON.stringify(seed.state));
const progress=createProgress('free-explore'),chapter=JSON.stringify(progress.state.chapter),story=progress.state.activeStory,coins=progress.state.coins;
const events=[];progress.subscribe(event=>events.push(event));
for(let i=0;i<8;i++)progress.track('wave',{ai:true});
progress.track('chat_ai');progress.track('visit',{place:'gift'});progress.track('checkpoint',{story,index:0});progress.track('connect_real');
assert.equal(progress.current(),null,'free exploration has no active mission');
assert.equal(JSON.stringify(progress.state.chapter),chapter,'paused missions do not complete in the background');
assert.equal(progress.state.activeStory,story,'saved story progress remains available for a future design');
assert.equal(progress.state.coins,coins,'no hidden mission rewards');assert.equal(events.filter(e=>e.toast).length,0,'no mission/achievement popups');
assert(progress.state.stamps.includes('gift'),'ordinary visit data is retained quietly');assert.equal(progress.state.waves,8);
assert(progress.spend(20));assert.equal(progress.state.coins,coins-20,'stall wallet still works');
const restored=createProgress('free-explore',{missionsEnabled:true});assert(restored.current(),'saved mission progress can be enabled explicitly later');
assert.equal(JSON.stringify(restored.state.chapter),chapter);
console.log('Free exploration passed: missions paused, no completion popups/rewards, previous progress preserved, normal visits/waves and wallet retained.');
